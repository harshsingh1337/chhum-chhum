export function formatPrice(paise) {
  const rupees = paise / 100;
  return '₹' + rupees.toLocaleString('en-IN');
}

export function getProductBySlug(slug) {
  return products.find((p) => p.slug === slug) || null;
}

export function getBestSellers() {
  return [...products.filter((p) => p.tag === 'Best Seller' || p.tag === 'New'), ...products.filter((p) => !p.tag)].slice(0, 4);
}

export function getRelatedProducts(currentSlug) {
  const current = products.find((p) => p.slug === currentSlug);
  if (!current) return products.slice(0, 4);
  // First: same product line (different color), then same fabric
  const sameLine = products.filter((p) => p.slug !== currentSlug && p.productLine === current.productLine);
  const sameFabric = products.filter((p) => p.slug !== currentSlug && p.productLine !== current.productLine && p.fabric === current.fabric);
  return [...sameLine, ...sameFabric].slice(0, 4);
}

